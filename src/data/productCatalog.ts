const ALL_PRODUCTS = Object.values(productCatalog);
export const SEARCH_MAX_RESULTS = 50;

type IndexedProduct = Product & { codeLower: string; descLower: string };

const INDEXED_PRODUCTS: IndexedProduct[] = ALL_PRODUCTS.map((p) => ({
  ...p,
  codeLower: p.code.toLowerCase(),
  descLower: p.description.toLowerCase(),
}));

const CODE_LOOKUP = new Map<string, Product>();
for (const p of INDEXED_PRODUCTS) {
  CODE_LOOKUP.set(p.code, p);
  CODE_LOOKUP.set(p.codeLower, p);
}

const PRODUCTS_BY_GROUP = new Map<string, Product[]>();
for (const p of INDEXED_PRODUCTS) {
  const list = PRODUCTS_BY_GROUP.get(p.group);
  if (list) list.push(p);
  else PRODUCTS_BY_GROUP.set(p.group, [p]);
}

const PRODUCT_GROUPS = [...PRODUCTS_BY_GROUP.keys()].sort((a, b) => a.localeCompare(b, "es"));

export function lookupProduct(code: string): Product | null {
  const trimmed = code.trim();
  if (!trimmed) return null;
  return CODE_LOOKUP.get(trimmed) ?? CODE_LOOKUP.get(trimmed.toLowerCase()) ?? null;
}

export function searchProducts(query: string, limit = SEARCH_MAX_RESULTS): Product[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const results: Product[] = [];
  for (const p of INDEXED_PRODUCTS) {
    if (p.codeLower.includes(q) || p.descLower.includes(q)) {
      results.push(p);
      if (results.length >= limit) break;
    }
  }
  return results;
}

export function productsByGroup(group: string): Product[] {
  return PRODUCTS_BY_GROUP.get(group) ?? [];
}

export function getProductGroups(): string[] {
  return PRODUCT_GROUPS;
}
